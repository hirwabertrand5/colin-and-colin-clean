async function main() {
  process.env.JWT_SECRET = 'isolated-retainer-tests'; delete process.env.RESEND_API_KEY;
  const binary = path.resolve(__dirname, '../../node_modules/.cache/mongodb-memory-server/test-mongod.exe');
  assert(existsSync(binary), 'A local test MongoDB binary is required.');
  const repl = await MongoMemoryReplSet.create({ binary: { systemBinary: binary, version: '7.0.14' }, replSet: { count: 1 }, instanceOpts: [{ launchTimeout: 120000 }] });
  let server: ReturnType<express.Express['listen']> | undefined, passed = 0;
  const pass = (label: string) => console.log(`PASS ${++passed}: ${label}`);
  try {
    await mongoose.connect(repl.getUri(), { dbName: 'retainer_accounting_verification' });
    await Promise.all(Object.values(mongoose.models).map((model) => model.init()));
    const manager = await User.create({ name: 'Manager', email: 'manager@retainer.invalid', role: 'managing_partner', passwordHash: 'test-only' });
    const alice = await User.create({ name: 'Alice', email: 'alice@retainer.invalid', role: 'associate', passwordHash: 'test-only' });
    const bob = await User.create({ name: 'Bob', email: 'bob@retainer.invalid', role: 'senior_associate', passwordHash: 'test-only' });
    const app = express(); app.use(express.json()); app.use('/retainers', retainerRoutes);
    app.get('/billing', authenticate, getBillingSummary); app.get('/profitability', authenticate, getProfitabilityReport);
    app.get('/earnings', authenticate, getStaffEarningsReport); app.get('/firm', authenticate, getFirmReports);
    app.get('/mine', authenticate, getMyProductivityEarningsReport);
    app.get('/staff-dashboard', authenticate, getStaffDashboardSummary);
    app.put('/cases/:id', authenticate, updateCase); app.delete('/cases/:id', authenticate, deleteCase);
    app.get('/cases/:caseId/earned-fees', authenticate, getCaseEarnedFees);
    server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
    const base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
    const request = async (url: string, body?: any, actor = manager, method?: string) => {
      const res = await fetch(`${base}${url}`, { method: method || (body === undefined ? 'GET' : 'POST'),
        headers: { Authorization: `Bearer ${jwt.sign({ id: String(actor._id) }, process.env.JWT_SECRET!)}`, 'Content-Type': 'application/json' },
        ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
      return { status: res.status, data: await res.json() as any };
    };
    const ok = async (url: string, body?: any, actor = manager) => { const r = await request(url, body, actor); assert.equal(r.status, 200, `${url}: ${JSON.stringify(r.data)}`); return r.data; };
    const fixedMonthlyAgreement = { name: 'Fixed monthly fee verification', clientName: 'Fixed retainer client', startDate: '2020-01-01', status: 'Active', monthlyFee: 750 };
    const createdAgreement = await request('/retainers', fixedMonthlyAgreement);
    assert.equal(createdAgreement.status, 201, createdAgreement.data.message);
    assert.equal(createdAgreement.data.billingModel, 'monthly');
    assert.equal(createdAgreement.data.monthlyFee, 750);
    for (const billingModel of ['prepaid', 'hybrid']) assert.equal((await request('/retainers', { ...fixedMonthlyAgreement, billingModel })).status, 400);
    pass('Retainer agreements use the fixed monthly fee without subscription or hybrid billing options');
    const agreement = await Retainer.create({ retainerNo: 'RET-TEST', name: 'Monthly legal services', clientName: 'Client Ltd', billingModel: 'monthly', status: 'Active', startDate: '2020-01-01', monthlyFee: 1000, billingDay: 1 });
    const url = `/retainers/${agreement._id}/periods`;
    const period = await ok(url, { month: '2020-01' }); const purl = `${url}/${period._id}`;
    assert.equal((await ok(url, { month: '2020-01' }))._id, period._id); assert.equal(await Period.countDocuments(), 1);
    pass('Opening a month is idempotent and snapshots its fixed fee');
    const nextMonth = await ok(url, { month: '2020-02' });
    assert.equal(nextMonth.fixedFee, period.fixedFee);
    pass('The same fixed monthly fee is recorded for each month under the retainer agreement');
    assert.equal((await request(url, { month: '2020-01' }, alice)).status, 403);
    assert.equal((await request(url, { month: '2020-13' })).status, 400);
    assert.equal((await request(url, { month: '2019-12' })).status, 400);
    pass('Management permission, month validation and agreement term are enforced');
    const template = await Template.create({ name: 'Retainer test', matterType: 'Retainer test', caseType: 'Transactional Cases',
      stages: [{ key: 'delivery', title: 'Delivery', order: 1, percentage: 100 }],
      steps: [{ key: 'service', title: 'Approved professional service', stageKey: 'delivery', order: 1, percentage: 100, actions: [], outputs: [], legalBasis: [], responsibleRole: 'Initiator' }] });
    const fixture = async (number: number, fee: number, status = 'Completed') => {
      const department = number === 2 ? { id: 'transactions_advisory', label: 'B. Transactions & Advisory' } : { id: 'dispute_resolution', label: 'A. Dispute Resolution' };
      const matter = await Case.create({ caseNo: `RET-M${number}`, parties: 'Client Ltd', caseType: 'Transactional Cases', status: 'In Progress', budget: String(fee),
        legalServicePath: [department],
        assignedTo: alice.name, caseAssignments: { initiator: alice.name, reviewer: bob.name, signerApprover: manager.name }, workflowTemplateId: template._id, matterType: template.matterType,
        billingArrangement: 'retainer', retainerId: agreement._id });
      const workflow = await Workflow.create({ caseId: matter._id, templateId: template._id, steps: [{ stepKey: 'service', title: `Service ${number}`, stageKey: 'delivery', order: 1, percentage: 100, status: 'Not Started', actions: [], outputs: [] }] });
      await Workflow.collection.updateOne({ _id: workflow._id }, { $set: { 'steps.0.status': status, 'steps.0.doneAt': new Date('2020-01-15T10:00:00Z'), 'steps.0.completedAt': new Date('2020-01-16T10:00:00Z') } });
      return matter;
    };
    const m1 = await fixture(1, 1500), m2 = await fixture(2, 1800), pending = await fixture(3, 100, 'Awaiting Approval');
    const assignedTeams = await ok(`/retainers/${agreement._id}/cases`);
    const pendingTeam = assignedTeams.cases.find((matter: any) => matter._id === String(pending._id)).team;
    assert.deepEqual(pendingTeam.map((member: any) => [member.role, member.name, member.tpaPercent]), [['Initiator', 'Alice', 5], ['Reviewer', 'Bob', 6], ['Signer/Approver', 'Manager', 10]]);
    assert(pendingTeam.every((member: any) => member.earnedFee == null && member.timelinessScore == null && member.qualityScore == null));
    const pendingCaseFees = await ok(`/cases/${pending._id}/earned-fees`);
    assert.deepEqual(pendingTeam, pendingCaseFees.team);
    pass('Linked case teams show real assigned names, roles and TPA before retainer services, matching the case workspace');
    await Workflow.collection.updateOne({ caseId: m1._id }, { $set: { 'steps.0.submittedAt': new Date('2020-02-02T10:00:00Z'), 'steps.0.completedAt': new Date('2020-02-03T10:00:00Z') } });
    const delayedApproval = await ok(`/retainers/${agreement._id}/service-candidates`);
    assert.equal(delayedApproval.find((w: any) => w.caseId === String(m1._id)).performedOn, '2020-01-15');
    pass('Later submission and approval do not move performed work into another service month');
    const service = (matter: any, fee: number, dept: string, staff: any = alice) => ({ caseId: String(matter._id), actionKey: 'service', ordinaryFee: fee, department: dept, contributors: [{ userId: String(staff._id), share: 100 }] });
    assert.equal((await request(`${purl}/services`, service(pending, 100, 'Dispute Resolution'))).status, 400);
    assert.equal((await request(`${purl}/services`, { ...service(m1, 1500, 'Dispute Resolution'), contributors: [{ userId: String(alice._id), share: 50 }] })).status, 400);
    pass('Unapproved work and invalid contributor percentages cannot enter production');
    assert.equal(delayedApproval.find((w: any) => w.caseId === String(m1._id)).department, 'Dispute Resolution');
    assert.equal(delayedApproval.find((w: any) => w.caseId === String(m2._id)).department, 'Transaction & Advisory');
    assert.equal((await request(`${purl}/services`, service(m1, 1500, 'Transaction & Advisory'))).status, 400);
    pass('Departmental production follows the matter’s selected department and rejects incorrect departmental allocation');
    await ok(`${purl}/services`, service(m1, 1500, 'Dispute Resolution'));
    let statement = await ok(`${purl}/services`, service(m2, 1800, 'Transaction & Advisory', bob));
    assert.equal(statement.allocation.workValue, 3300); assert.equal(statement.allocation.actualReceived, 0); assert.equal(statement.allocation.staffTpa, 183);
    assert.equal(statement.allocation.allocableRevenue, 0);
    const linkedMatters = await ok(`/retainers/${agreement._id}/cases`);
    assert.equal(linkedMatters.summary.ordinaryWorkValue, 3300);
    assert.equal(linkedMatters.cases.find((m: any) => m._id === String(m1._id)).department, 'Dispute Resolution');
    assert.equal(linkedMatters.cases.find((m: any) => m._id === String(m2._id)).ordinaryWorkValue, 1800);
    pass('Production and staff TPA accrue independently of received revenue');
    const unpaidProfit = await ok('/profitability?from=2020-01-01&to=2020-01-31');
    const unpaidFirm = await ok('/firm?from=2020-01-01&to=2020-01-31');
    assert.equal(unpaidProfit.firm.totalReceivables, 1000);
    assert.equal(Object.values(unpaidProfit.ageing).reduce((n: number, x: any) => n + Number(x), 0), 1000);
    assert.equal(unpaidFirm.ageingReport.reduce((n: number, x: any) => n + x.amount, 0), 1000);
    pass('Unpaid monthly fees appear in both receivables and ageing totals');
    assert.equal((await request(`${purl}/services`, service(m1, 1500, 'Dispute Resolution'))).status, 409);
    const claimed = await Case.findById(m1._id).lean();
    const standard = calculateCollectedKeyActionEarnings({ matter: claimed, template, workflowInstance: await Workflow.findOne({ caseId: m1._id }).lean(), collectedAmount: 100000 });
    assert.equal(standard.completedActions.length, 0);
    pass('Stable action claims prevent duplicate services and ordinary TPA for covered work');
    const forgedEdit = await request(`/cases/${m1._id}`, { retainerCoveredActionKeys: [] }, manager, 'PUT');
    assert.equal(forgedEdit.status, 200, forgedEdit.data.message);
    assert((await Case.findById(m1._id))!.retainerCoveredActionKeys!.includes('service'));
    assert.equal((await request(`/cases/${m1._id}`, undefined, manager, 'DELETE')).status, 409);
    pass('Generic matter editing cannot remove accounting claims, and deletion preserves accounting history');
    statement = await ok(`${purl}/receipts`, { amount: 1000, receivedOn: '2020-01-20', reference: 'BANK-RET-1' });
    assert.deepEqual(statement.allocation.departments.map((d: any) => d.allocatedRevenue), [455, 545]);
    assert.equal(statement.allocation.utilisation, 330); assert.equal(statement.allocation.excessServiceValue, 2300);
    assert.equal(statement.allocation.substantialOverutilisation, true);
    assert.equal(await Invoice.countDocuments(), 0);
    pass('PDF example allocates actual revenue proportionately and never invoices excess production');
    assert.equal((await request(`${purl}/receipts`, { amount: 1000, receivedOn: '2020-01-20', reference: 'bank-ret-1' })).status, 409);
    pass('Case-insensitive payment references prevent duplicate receipt entry');
    const range = 'from=2020-01-01&to=2020-01-31';
    let billing = await ok(`/billing?${range}`), profit = await ok(`/profitability?${range}`), firm = await ok(`/firm?${range}`), earnings = await ok(`/earnings?${range}`);
    assert.equal(billing.collected, 1000); assert.equal(profit.firm.recognisedCollectedRevenue, 1000); assert.equal(firm.kpis.collected, 1000);
    assert.equal(billing.billed, 1000); assert.equal(profit.firm.billed, 1000); assert.equal(firm.kpis.billed, 1000);
    assert.equal(earnings.totals.earnedFee, 183); assert.equal(firm.productivitySummary.totalFeeEarned, 183);
    assert.equal(profit.firm.netProfit, 817); assert.equal(billing.netProfit, 817); assert.equal(firm.kpis.netProfit, 817);
    assert.equal(profit.matterRows.reduce((n: number, r: any) => n + r.collected, 0), 1000);
    assert.equal(profit.clientRows.reduce((n: number, r: any) => n + r.billed, 0), 1000);
    assert.equal(firm.months.reduce((n: number, r: any) => n + r.collected, 0), 1000);
    assert.equal(firm.clientProfitability.reduce((n: number, r: any) => n + r.collected, 0), 1000);
    pass('Billing, profitability, Staff TPA and Management Reports reconcile revenue and TPA');
    const personal = await ok(`/mine?${range}`, undefined, bob); assert.equal(personal.selectedMember.feesEarned, 108);
    const dashboard = await ok(`/staff-dashboard?${range}`, undefined, bob); assert.equal(dashboard.feesEarnedTotal, 108);
    pass('Contributing staff see the same retainer earnings in their personal report');
    const invoice = await Invoice.create({ caseId: m1._id, invoiceNo: 'INV-RET-IMPORT', year: 2020, seqYear: 1, seqCase: 1, date: '2020-01-22', amount: 500, status: 'Paid' });
    await Invoice.collection.updateOne({ _id: invoice._id }, { $set: { updatedAt: new Date('2020-01-22T10:00:00Z') } });
    await ok(`${purl}/receipts`, { amount: 999, receivedOn: '2020-01-01', reference: 'ignored', sourceInvoiceId: String(invoice._id) });
    billing = await ok(`/billing?${range}`); profit = await ok(`/profitability?${range}`); firm = await ok(`/firm?${range}`);
    assert.equal(billing.collected, 1500); assert.equal(profit.firm.recognisedCollectedRevenue, 1500); assert.equal(firm.kpis.collected, 1500);
    assert.equal(billing.billed, 1000); assert.equal(billing.retainer.staffTpa, 183);
    pass('Transferring an existing paid invoice reclassifies its cash without duplicating billing or earnings');
    const close = await ok(`${purl}/actions/close`, {}); assert.equal(close.status, 'Closed');
    assert.equal((await request(`${purl}/services`, service(pending, 100, 'Dispute Resolution'))).status, 409);
    await ok(`${purl}/receipts`, { amount: 100, receivedOn: '2020-02-03', reference: 'LATE-RET-2' });
    const late = await ok('/billing?from=2020-02-01&to=2020-02-29');
    assert.equal(late.collected, 100); assert.equal(late.retainer.staffTpa, 0);
    assert.equal((await ok(`/earnings?${range}`)).totals.earnedFee, 183);
    pass('Closed months lock services; late receipts use receipt dates without earning TPA twice');
    assert.equal((await request(`${purl}/actions/reopen`, { reason: 'x' })).status, 400);
    await ok(`${purl}/actions/reopen`, { reason: 'Correct mistaken receipt' });
    statement = await ok(purl);
    await ok(`${purl}/actions/void-receipt`, { receiptId: statement.receipts[0]._id, reason: 'Mistaken payment reference' });
    assert.equal((await ok(`/billing?${range}`)).collected, 500);
    assert.equal((await ok(purl)).receipts.length, 3);
    pass('Reversals preserve receipt history and remove reversed cash from reports');
    await ok(`${purl}/actions/restore-receipt`, { receiptId: statement.receipts[0]._id, reason: 'Restore verified bank payment' });
    assert.equal((await ok(`/billing?${range}`)).collected, 1500);
    await ok(`${purl}/actions/amend-fee`, { fixedFee: 1200, reason: 'Agreed monthly fee amendment' });
    assert.equal((await ok(purl)).fixedFee, 1200);
    assert.equal((await Retainer.findById(agreement._id))!.monthlyFee, 1000);
    pass('Receipt restoration and audited monthly fee amendments preserve agreement defaults');
    const firstService = (await ok(purl)).allocation.services.find((s: any) => String(s.caseId) === String(m1._id));
    await ok(`${purl}/actions/void-service`, { serviceId: firstService._id, reason: 'Correct contributing staff proportions' });
    const replacement = await ok(`${purl}/services`, { ...service(m1, 1500, 'Dispute Resolution'), contributors: [{ userId: String(alice._id), share: 40 }, { userId: String(bob._id), share: 60 }] });
    assert.equal(replacement.allocation.workValue, 3300); assert.equal(replacement.allocation.staffTpa, 192);
    assert.equal(replacement.services.filter((s: any) => s.voidedAt).length, 1);
    pass('Replacing reversed work corrects staff shares without duplicating production');
    await User.updateOne({ _id: bob._id }, { $set: { role: 'intern' } });
    assert.equal((await ok(`/earnings?${range}`)).totals.earnedFee, 192);
    pass('Historical retainer TPA snapshots survive later staff role changes');
    const m4 = await fixture(4, 200);
    await Ledger.collection.insertOne({ caseId: m4._id, keyActionKey: 'service', earnedFee: 10, entryKey: 'historic-ordinary-earning' });
    assert.equal((await request(`${purl}/services`, service(m4, 200, 'Dispute Resolution'))).status, 409);
    pass('Existing positive ordinary earnings block duplicate retainer recognition');
    const under = allocateRetainer({ fixedFee: 1000, services: [{ ordinaryFee: 500, department: 'Dispute Resolution', caseId: 'one', contributors: [{ share: 100, tpaPercent: 5 }] }] }, [{ amount: 1000 }]);
    assert.equal(under.allocableRevenue, 500); assert.equal(under.firmUnutilisedRevenue, 500); assert.equal(under.staffTpa, 25);
    assert.equal(allocateRetainer({ fixedFee: 1000, services: [] }, [{ amount: 1000 }]).firmUnutilisedRevenue, 1000);
    pass('Underutilisation and zero-work months retain unused receipts at firm level');
    const cashTimeline = allocateRetainer({ fixedFee: 1000, services: [{ _id: 's', ordinaryFee: 500, department: 'Dispute Resolution', caseId: 'one', contributors: [{ share: 100, tpaPercent: 5 }] }] }, [{ _id: 'first', amount: 300, receivedOn: '2020-01-20' }, { _id: 'late', amount: 700, receivedOn: '2020-02-03' }]);
    assert.deepEqual(cashTimeline.receiptAllocations.map((r) => r.serviceCredits[0]), [300, 200]);
    assert.deepEqual(cashTimeline.receiptAllocations.map((r) => r.firmUnutilisedRevenue), [0, 500]);
    pass('Late partial receipts allocate only remaining work and reconcile across reporting windows');
    for (let total = 0; total < 200; total++) assert.equal(apportion(total, [1, 1, 1, 7]).reduce((n, x) => n + x, 0), total);
    pass('Whole RWF allocation reconciles exactly across rounding edge cases');
    const before = await Receipt.countDocuments(); await ok(`/earnings?${range}&persist=true`); await ok(`/earnings?${range}&persist=true`);
    assert.equal(await Receipt.countDocuments(), before);
    assert.equal(await Ledger.countDocuments({ assignmentRole: 'retainer-contributor' }), 0);
    pass('Repeated reports do not create duplicate receipts or a second retainer earnings ledger');
    await ok(url, { month: '2020-02' });
    const arrears = await ok('/firm?from=2020-03-01&to=2020-03-31');
    assert.equal(arrears.kpis.outstanding, 1000);
    assert.equal(arrears.ageingReport.reduce((n: number, x: any) => n + x.amount, 0), 1000);
    assert.equal(arrears.clientProfitability.reduce((n: number, x: any) => n + x.outstanding, 0), 1000);
    pass('Historical retainer arrears remain visible in later periods without duplicate billing');
    await PettyCashExpense.create([
      { fundId: new mongoose.Types.ObjectId(), date: '2020-01-15', title: 'Client filing cost', amount: 300, refundAmount: 50, chargeType: 'client', caseId: m1._id, createdByName: manager.name },
      { fundId: new mongoose.Types.ObjectId(), date: '2020-01-15', title: 'Fully refunded client cost', amount: 80, refundAmount: 100, chargeType: 'client', caseId: m2._id, createdByName: manager.name },
      { fundId: new mongoose.Types.ObjectId(), date: '2020-01-15', title: 'Firm overhead', amount: 100, chargeType: 'internal', caseId: m1._id, createdByName: manager.name },
    ]);
    const otherPeriod = await ok(`/retainers/${createdAgreement.data._id}/periods`, { month: '2020-01' });
    await ok(`/retainers/${createdAgreement.data._id}/periods/${otherPeriod._id}/receipts`, { amount: 750, receivedOn: '2020-01-10', reference: 'OTHER-RETAINER' });
    let workspace = await ok(`/retainers/${agreement._id}/cases`);
    assert.equal(workspace.accounting.recordedMonths, 2);
    assert.equal(workspace.accounting.fixedFees, 2200);
    assert.equal(workspace.accounting.actualReceived, 1600);
    assert.equal(workspace.accounting.outstanding, 1000);
    assert.equal(workspace.accounting.overpayment, 400);
    assert.equal(workspace.accounting.workValue, 3300);
    assert.equal(workspace.accounting.staffTpa, 192);
    const caseFees = await ok(`/cases/${m1._id}/earned-fees`);
    assert.deepEqual(workspace.cases.find((matter: any) => matter._id === String(m1._id)).team, caseFees.team);
    assert.equal(workspace.accounting.services.length, 2);
    assert.equal(workspace.accounting.departments.reduce((sum: number, d: any) => sum + d.allocatedRevenue, 0), 1600);
    const firstCase = workspace.cases.find((matter: any) => matter._id === String(m1._id));
    assert.equal(firstCase.directMatterCosts, 250);
    assert.equal(firstCase.retainerRevenue, 727);
    assert.equal(firstCase.staffTpa, 84);
    assert.equal(firstCase.netContribution, 393);
    assert.deepEqual(firstCase.contributors.map((member: any) => [member.name, member.earnedTpa]), [['Bob', 54], ['Alice', 30]]);
    assert.equal(workspace.cases.find((matter: any) => matter._id === String(m2._id)).directMatterCosts, 0);
    pass('Workspace totals reconcile multiple months, shared staff earnings, refunds and reversals, and exclude other retainers');
    await ok(`/retainers/cases/${m1._id}/link`, {});
    workspace = await ok(`/retainers/${agreement._id}/cases`);
    assert(!workspace.cases.some((matter: any) => matter._id === String(m1._id)));
    assert.equal(workspace.accounting.workValue, 3300);
    assert.equal(workspace.accounting.staffTpa, 192);
    assert.equal(workspace.accounting.actualReceived, 1600);
    pass('Unlinking a case preserves recorded retainer revenue and staff earnings');
    console.log(`Retainer accounting verification: ${passed} checks passed.`);
  } finally {
    if (server) await new Promise<void>((resolve) => server!.close(() => resolve()));
    await mongoose.disconnect(); await repl.stop();
  }
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
