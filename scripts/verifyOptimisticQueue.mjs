import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { transform } from 'esbuild';
const source = await readFile(new URL('../src/utils/optimisticMutationQueue.ts', import.meta.url), 'utf8');
const compiled = await transform(source, { loader: 'ts', format: 'esm', target: 'es2022' });
const { OptimisticMutationQueue } = await import(`data:text/javascript;base64,${Buffer.from(compiled.code).toString('base64')}`);
const deferred = () => { let resolve, reject; const promise = new Promise((ok, fail) => { resolve = ok; reject = fail; }); return { promise, resolve, reject }; };
const drain = () => new Promise(resolve => setImmediate(resolve));
let visible, keys, saved = [], failures = [], settled = [];
const queue = new OptimisticMutationQueue({ change: (value, pending) => { visible = value; keys = pending; }, failed: message => failures.push(message), settled: value => settled.push(value) });
queue.reset(0);
const first = deferred(), second = deferred(), third = deferred();
const edit = (key, response) => ({ key, apply: value => value + 1, save: () => { saved.push(key); return response.promise; } });
queue.enqueue(edit('first', first)); queue.enqueue(edit('second', second)); queue.enqueue(edit('third', third));
assert.equal(visible, 3); assert.deepEqual(saved, ['first']);
first.resolve(10); await drain();
assert.equal(visible, 12, 'A server response must preserve later optimistic edits');
assert.deepEqual(saved, ['first', 'second']);
second.resolve(11); await drain();
assert.equal(visible, 12); third.reject(new Error('Rejected third save')); await drain();
assert.equal(visible, 11, 'Rollback preserves earlier successful saves'); assert.deepEqual(keys, []);
assert.equal(failures.length, 1); assert.deepEqual(settled, [11]);
queue.reset(0); saved = []; const failed = deferred(), cancelled = deferred();
queue.enqueue(edit('failed', failed)); queue.enqueue(edit('dependent', cancelled));
failed.reject(new Error('First save failed')); await drain();
assert.deepEqual(saved, ['failed'], 'Dependent edits must never be sent after an earlier failure');
assert.equal(visible, 0); assert.match(failures.at(-1), /Later queued changes were cancelled/);
queue.reset(100); const stale = deferred(); queue.enqueue(edit('stale', stale));
queue.dispose(); queue.reset(200); stale.resolve(999); await drain();
const next = deferred(); queue.enqueue(edit('next', next)); assert.equal(visible, 201, 'A disposed operation must not overwrite a new case');
next.resolve(201); await drain();
console.log('PASS: immediate edits, serial saves, server reconciliation, rollback, dependent cancellation and case-change isolation');
